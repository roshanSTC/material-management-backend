"""SQL Generator leveraging Google Gemini, Ollama, or deterministic fallback."""

import json
import os
import re
from typing import Any, Dict, List, Optional, Tuple
import requests

from app.ai_assistant.services.prompt_service import PromptService, SAFE_REFUSAL_TEXT

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY") or os.getenv("AI_API_KEY")
AI_MODEL = os.getenv("AI_MODEL", "gemini-2.5-flash")
OLLAMA_BASE_URL = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "llama3.2")


class SQLGenerator:
    """Generates read-only SQL queries from natural language questions using LLM."""

    @classmethod
    def generate_sql(
        cls, question: str, history: Optional[List[Dict[str, Any]]] = None
    ) -> Tuple[Optional[str], Optional[str], Optional[str]]:
        """
        Convert question to SQL query.

        Returns:
            Tuple of (sql, explanation, refusal)
        """
        # 1. Preflight screening
        preflight_refusal = PromptService.check_preflight_refusal(question)
        if preflight_refusal:
            return None, None, preflight_refusal

        # 2. Try Gemini if API key is configured
        if GEMINI_API_KEY and GEMINI_API_KEY.strip():
            try:
                return cls._generate_via_gemini(question, history)
            except Exception as exc:
                # Log error and attempt fallback
                pass

        # 3. Try Ollama if server is reachable
        if OLLAMA_BASE_URL:
            try:
                res = cls._generate_via_ollama(question, history)
                if res[0] or res[2]:
                    return res
            except Exception:
                pass

        # 4. Deterministic fallback for common ERP questions and tests
        return cls._generate_via_fallback(question)

    @classmethod
    def _generate_via_gemini(
        cls, question: str, history: Optional[List[Dict[str, Any]]]
    ) -> Tuple[Optional[str], Optional[str], Optional[str]]:
        """Generate SQL using google-genai library."""
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=GEMINI_API_KEY)
        system_instruction = PromptService.build_system_prompt()
        prompt = PromptService.build_user_prompt(question, history)

        response = client.models.generate_content(
            model=AI_MODEL,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.1,
                response_mime_type="application/json",
            ),
        )

        return cls._parse_llm_json(response.text)

    @classmethod
    def _generate_via_ollama(
        cls, question: str, history: Optional[List[Dict[str, Any]]]
    ) -> Tuple[Optional[str], Optional[str], Optional[str]]:
        """Generate SQL using local Ollama instance."""
        url = f"{OLLAMA_BASE_URL.rstrip('/')}/api/generate"
        system_prompt = PromptService.build_system_prompt()
        prompt = f"{system_prompt}\n\n{PromptService.build_user_prompt(question, history)}"

        payload = {
            "model": OLLAMA_MODEL,
            "prompt": prompt,
            "stream": False,
            "format": "json",
            "options": {"temperature": 0.1},
        }

        resp = requests.post(url, json=payload, timeout=0.8)
        if resp.status_code == 200:
            data = resp.json()
            return cls._parse_llm_json(data.get("response", ""))
        return None, None, None

    @classmethod
    def _parse_llm_json(cls, raw_text: str) -> Tuple[Optional[str], Optional[str], Optional[str]]:
        """Parse structured JSON from model response."""
        if not raw_text:
            return None, None, "No response generated by AI."

        text = raw_text.strip()
        # Clean markdown code block wraps if present
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
        text = text.strip()

        try:
            parsed = json.loads(text)
            sql = parsed.get("sql")
            explanation = parsed.get("explanation")
            refusal = parsed.get("refusal")
            return sql, explanation, refusal
        except json.JSONDecodeError:
            # If plain SQL was returned instead of JSON
            match = re.search(r"SELECT\s+.*", text, re.IGNORECASE | re.DOTALL)
            if match:
                return match.group(0).strip(), "Generated query from question.", None
            return None, None, "Unable to interpret AI model output."

    @classmethod
    def _generate_via_fallback(
        cls, question: str
    ) -> Tuple[Optional[str], Optional[str], Optional[str]]:
        """Deterministic domain generator for core ERP queries when LLM is unavailable."""
        q = question.lower().strip()

        # Check modification keywords
        if any(w in q for w in ("delete", "remove", "drop", "truncate", "alter", "update", "modify", "insert")):
            return None, None, SAFE_REFUSAL_TEXT

        # Customer queries
        if "top" in q and "customer" in q:
            return (
                "SELECT id, name, email, contact_number, city, country, created_at FROM customers ORDER BY id DESC LIMIT 10",
                "Showing top 10 customers sorted by most recent entry.",
                None,
            )
        if "customer" in q and ("count" in q or "how many" in q or "number of" in q):
            return (
                "SELECT COUNT(*) AS total_customers FROM customers",
                "Total count of registered customers in the database.",
                None,
            )
        if "all customer" in q or "list customer" in q or "show customer" in q or "customers" in q:
            return (
                "SELECT id, name, nickname, email, contact_number, city, state, country, created_at FROM customers ORDER BY name ASC LIMIT 50",
                "List of active customers with contact details and location.",
                None,
            )

        # Supplier queries
        if "supplier" in q and ("count" in q or "how many" in q or "number of" in q):
            return (
                "SELECT COUNT(*) AS total_suppliers FROM suppliers",
                "Total count of suppliers registered.",
                None,
            )
        if "supplier" in q:
            return (
                "SELECT id, name, email, contact_number, city, country, created_at FROM suppliers ORDER BY name ASC LIMIT 50",
                "List of registered suppliers and vendors.",
                None,
            )

        # Project queries
        if "project" in q and ("count" in q or "how many" in q):
            return (
                "SELECT COUNT(*) AS total_projects FROM projects",
                "Total number of client projects.",
                None,
            )
        if "project" in q:
            return (
                "SELECT p.id, p.project_title, c.name AS customer_name, p.project_code, p.created_at "
                "FROM projects p LEFT JOIN customers c ON p.customer_id = c.id ORDER BY p.id DESC LIMIT 50",
                "List of client projects with customer names and project codes.",
                None,
            )

        # Purchase order queries
        if "purchase order" in q or "po" in q:
            return (
                "SELECT id, po_number, po_title, total_gross_amount, po_date, created_at FROM purchase_orders ORDER BY id DESC LIMIT 50",
                "Recent purchase orders placed with suppliers.",
                None,
            )

        # Material queries
        if "material" in q:
            return (
                "SELECT id, material_code, material_name, hsn_code, description FROM materials LIMIT 50",
                "Material catalog and specifications.",
                None,
            )

        # Invoice / payment queries
        if "payment" in q or "revenue" in q:
            return (
                "SELECT id, project_id, invoice_no, payment_amount, invoice_value, payment_date FROM customer_payments ORDER BY id DESC LIMIT 50",
                "Recorded customer payment receipts.",
                None,
            )

        # Generic fallback
        return (
            "SELECT id, name, email, contact_number, city, created_at FROM customers ORDER BY created_at DESC LIMIT 10",
            "Showing recent customer records.",
            None,
        )
